OK = "01nicklas07@gmail.com"


def collapse(html: str) -> str:
    return re.sub(r">\s+<", "><", html).strip()


def shimbun(body, **kw):
    return Request(to=OK, subject="Shimbun", body=body, content_type="markdown", theme="shimbun", dry_run=True, **kw)


async def run(req, tcfg, relay, sender):
    return await process(req, tcfg, relay, sender=sender)


def full_html(store, theme, body):
    return store.render(store.resolve(theme), body, "s").html


# -- parity and escaping ------------------------------------------------------


def test_parity_with_vendored_render_html(digest_md):
    store = ThemeStore(THEMES / "nonexistent", THEMES)
    sections = yaml.safe_load((THEMES / "shimbun" / "theme.yaml").read_text())["sections"]
    expected = render_html(parse_dialect(digest_md, [s["label"] for s in sections]), sections)
    assert collapse(full_html(store, "shimbun", digest_md)) == collapse(expected)


def test_script_in_headline_and_tldr_is_escaped(tcfg, digest_md):
    evil = digest_md.replace(
        "CISA warns of hackers now exploiting critical Node2Shell flaw", "<script>alert(1)</script> headline"
    ).replace("Point release.", "<script>alert(1)</script> Point release.").replace(
        "> CISA added", "> <script>alert(1)</script> CISA added"
    )
    store = ThemeStore(tcfg.themes_dir, tcfg.themes_default_dir)
    html = full_html(store, "shimbun", evil)
    assert "<script>" not in html
    assert html.count("&lt;script&gt;alert(1)&lt;/script&gt;") == 3
    assert find_violations(html, trusted_template=True) == []


def test_footer_values_are_escaped(theme_dirs, digest_md):
    override, default = theme_dirs
    store = ThemeStore(override, default)
    html = full_html(store, "shimbun", digest_md.replace('title: "Shark-no-Shimbun"', 'title: "<b>Shimbun</b>"'))
    assert "Generated by Claude Code Routine &middot; &lt;b&gt;Shimbun&lt;/b&gt;" in html


# -- template safety ----------------------------------------------------------


def override_template(override, theme, text, filename="email.html.j2"):
    return write(override / theme / filename, text)


async def test_template_injecting_script_is_rejected(tcfg, relay, sender, digest_md):
    override_template(tcfg.themes_dir, "shimbun", "<html><body><p>{{ digest.title }}</p><script>alert(1)</script></body></html>")
    r = await run(shimbun(digest_md), tcfg, relay, sender)
    assert r["code"] == "E_UNSAFE_CONTENT" and "<script> element" in r["details"]


async def test_template_style_import_is_rejected(tcfg, relay, sender, digest_md):
    override_template(tcfg.themes_dir, "shimbun", "<html><head><style>@import url(https://example.com/x.css);</style></head><body>{{ digest.title }}</body></html>")
    r = await run(shimbun(digest_md), tcfg, relay, sender)
    assert r["code"] == "E_UNSAFE_CONTENT" and "<style> element contains blocked CSS" in r["details"]


async def test_template_conditional_td_onclick_is_rejected(tcfg, relay, sender, digest_md):
    override_template(tcfg.themes_dir, "shimbun", '<html><body><!--[if mso]><td onclick="x()">{{ digest.title }}</td><![endif]--></body></html>')
    r = await run(shimbun(digest_md), tcfg, relay, sender)
    assert r["code"] == "E_UNSAFE_CONTENT"
    assert any("onclick" in d and "conditional comment" in d for d in r["details"])


@pytest.fixture
def css_server():
    """Local HTTP server that records every request, to prove nothing is fetched."""
    hits = []

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            hits.append(self.path)
            self.send_response(200)
            self.send_header("Content-Type", "text/css")
            self.end_headers()
            self.wfile.write(b"p { color: red }")

        def log_message(self, *args):
            pass

    srv = http.server.HTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    yield f"http://127.0.0.1:{srv.server_port}", hits
    srv.shutdown()


async def test_link_stylesheet_with_inline_css_is_rejected_without_fetching(tcfg, relay, sender, css_server):
    base, hits = css_server
    assert yaml.safe_load((tcfg.themes_default_dir / "default" / "theme.yaml").read_text())["inline_css"] is True
    override_template(tcfg.themes_dir, "default", f'<html><head><link rel="stylesheet" href="{base}/x.css"></head><body>{{{{ content }}}}</body></html>')
    r = await run(Request(to=OK, subject="s", body="# hi", content_type="markdown", dry_run=True), tcfg, relay, sender)
    assert r["code"] == "E_UNSAFE_CONTENT" and "<link> element" in r["details"]
    assert hits == []


def test_inliner_never_fetches_remote_stylesheets(css_server):
    base, hits = css_server
    out = themes_mod._inliner.inline(
        f'<html><head><link rel="stylesheet" href="{base}/x.css"><style>@import url({base}/y.css); p {{ margin: 0 }}</style></head><body><p>x</p></body></html>'
    )
    assert hits == []
    assert "<link" not in out and "@import" not in out


# -- overrides and reload -----------------------------------------------------


async def test_override_wins_then_delete_falls_back(tcfg, relay, sender, digest_md):
    store = ThemeStore(tcfg.themes_dir, tcfg.themes_default_dir)
    tpl = (tcfg.themes_default_dir / "shimbun" / "email.html.j2").read_text()
    path = override_template(tcfg.themes_dir, "shimbun", tpl.replace("TL;DR: this week", "OVERRIDE-MARKER"))
    assert "OVERRIDE-MARKER" in full_html(store, "shimbun", digest_md)
    path.unlink()
    html = full_html(store, "shimbun", digest_md)
    assert "OVERRIDE-MARKER" not in html and "TL;DR: this week" in html


def test_override_added_after_first_render_is_picked_up(tcfg, digest_md):
    store = ThemeStore(tcfg.themes_dir, tcfg.themes_default_dir)
    assert "ADDED-LATER" not in full_html(store, "shimbun", digest_md)
    tpl = (tcfg.themes_default_dir / "shimbun" / "email.html.j2").read_text()
    override_template(tcfg.themes_dir, "shimbun", tpl.replace("TL;DR: this week", "ADDED-LATER"))
    assert "ADDED-LATER" in full_html(store, "shimbun", digest_md)


def test_per_file_fallback_uses_default_theme_yaml(tcfg, digest_md):
    tpl = (tcfg.themes_default_dir / "shimbun" / "email.html.j2").read_text()
    override_template(tcfg.themes_dir, "shimbun", tpl.replace("TL;DR: this week", "ONLY-TEMPLATE"))
    assert not (tcfg.themes_dir / "shimbun" / "theme.yaml").exists()
    store = ThemeStore(tcfg.themes_dir, tcfg.themes_default_dir)
    out = store.render(store.resolve("shimbun"), digest_md, "s")
    assert "ONLY-TEMPLATE" in out.html
    assert "background:#fcebeb;color:#791f1f" in out.html  # chip_style from the default theme.yaml
    assert out.items == {"Security": 1, "Releases": 1}


def test_editing_override_between_renders(tcfg, digest_md):
    store = ThemeStore(tcfg.themes_dir, tcfg.themes_default_dir)
    tpl = (tcfg.themes_default_dir / "shimbun" / "email.html.j2").read_text()
    path = override_template(tcfg.themes_dir, "shimbun", tpl.replace("TL;DR: this week", "EDIT-ONE"))
    assert "EDIT-ONE" in full_html(store, "shimbun", digest_md)
    path.write_text(tpl.replace("TL;DR: this week", "EDIT-TWO"), encoding="utf-8")
    st = path.stat()
    os.utime(path, ns=(st.st_atime_ns, st.st_mtime_ns + 2_000_000_000))  # independent of mtime resolution
    html = full_html(store, "shimbun", digest_md)
    assert "EDIT-TWO" in html and "EDIT-ONE" not in html


def test_theme_yaml_override_applies(tcfg, digest_md):
    cfg_text = (tcfg.themes_default_dir / "shimbun" / "theme.yaml").read_text()
    write(tcfg.themes_dir / "shimbun" / "theme.yaml", cfg_text.replace("#a32d2d", "#123456"))
    store = ThemeStore(tcfg.themes_dir, tcfg.themes_default_dir)
    html = full_html(store, "shimbun", digest_md)
    assert "#123456" in html and "#a32d2d" not in html


# -- errors -------------------------------------------------------------------


@pytest.mark.parametrize(
    "template,needle",
    [
        ("<p>{% if %}</p>", "line 1"),  # syntax error
        ("<p>\n{{ no_such_variable }}</p>", "'no_such_variable' is undefined"),
        ("<p>{{ ''.__class__ }}</p>", "SecurityError"),
        ("<p>{{ digest.title.__class__.__mro__ }}</p>", "SecurityError"),
    ],
)
async def test_template_errors_map_to_e_theme_template(tcfg, relay, sender, digest_md, template, needle):
    override_template(tcfg.themes_dir, "shimbun", template)
    r = await run(shimbun(digest_md), tcfg, relay, sender)
    assert r["code"] == "E_THEME_TEMPLATE", r
    assert "shimbun/email.html.j2 (override)" in r["message"] and needle in r["message"], r["message"]


async def test_undefined_variable_reports_line(tcfg, relay, sender, digest_md):
    override_template(tcfg.themes_dir, "shimbun", "<p>ok</p>\n<p>ok</p>\n<p>{{ nope }}</p>")
    r = await run(shimbun(digest_md), tcfg, relay, sender)
    assert r["message"].startswith("shimbun/email.html.j2 (override) line 3:"), r["message"]


@pytest.mark.parametrize(
    "theme_yaml,needle",
    [
        ("input: shimbun\nsections: [unclosed\n", "invalid YAML"),
        ("- just\n- a list\n", "must be a mapping"),
        ("input: carrier-pigeon\n", "'input' must be one of"),
        ("input: shimbun\nsections: []\n", "'sections' must be a non-empty list"),
        ("input: markdown\nallowed_recipients: someone@example.com\n", "'allowed_recipients' must be a list"),
    ],
)
async def test_invalid_theme_yaml(tcfg, relay, sender, digest_md, theme_yaml, needle):
    write(tcfg.themes_dir / "shimbun" / "theme.yaml", theme_yaml)
    r = await run(shimbun(digest_md), tcfg, relay, sender)
    assert r["code"] == "E_THEME_TEMPLATE" and "shimbun/theme.yaml (override)" in r["message"] and needle in r["message"], r


