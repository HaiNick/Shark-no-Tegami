def test_startup_check_reports_broken_override_without_raising(theme_dirs, digest_md):
    override, default = theme_dirs
    write(override / "shimbun" / "email.html.j2", "{{ undefined_thing }}")
    write(override / "alert" / "schema.json", "{not json")
    problems = ThemeStore(override, default).self_check(digest_md)
    assert len(problems) == 2
    assert any(p.startswith("theme 'shimbun': E_THEME_TEMPLATE") for p in problems)
    assert any(p.startswith("theme 'alert': E_THEME_TEMPLATE") and "schema.json (override)" in p for p in problems)
